#!/usr/bin/env python3
import json,pathlib,re
root=pathlib.Path(__file__).resolve().parents[2]
en=json.loads((root/'Resources/Localization/en.json').read_text());inv=json.loads((root/'Resources/Localization/inventory.json').read_text())
assert set(en)==set(inv),(set(inv)-set(en),set(en)-set(inv))
for k,v in en.items():
 assert not re.search('[\u3400-\u9fff]',v),k
 assert sorted(re.findall(r'\{\d+\}',k))==sorted(re.findall(r'\{\d+\}',v)),k
entries='\n'.join('        '+json.dumps(k,ensure_ascii=False)+': '+json.dumps(v,ensure_ascii=False)+',' for k,v in en.items())
source='''// Generated by tools/localization/generate.py. Edit Resources/Localization/en.json.
import Foundation

public enum AppLanguage {
    public enum Language: String, Sendable { case chinese = "zh-Hans", english = "en" }
    public static func choose(_ preferred: [String]) -> Language {
        for tag in preferred {
            if tag.lowercased().hasPrefix("zh") { return .chinese }
            if tag.lowercased().hasPrefix("en") { return .english }
        }
        return .english
    }
    public static let current: Language = {
        if let test = ProcessInfo.processInfo.environment["MACOSX_TEST_LANGUAGE"] {
            return choose([test])
        }
        return choose(Locale.preferredLanguages)
    }()
    public static func text(_ key: String, _ arguments: String...) -> String {
        localized(key, language: current, arguments: arguments)
    }
    public static func localized(_ key: String, language: Language, arguments: [String] = []) -> String {
        let template = language == .chinese ? key : (english[key] ?? key)
        // Replace placeholders in the template only, never inside user-provided arguments.
        let pieces = template.components(separatedBy: "{")
        return pieces.enumerated().map { index, piece in
            guard index > 0 else { return piece }
            guard let end = piece.firstIndex(of: "}"), let slot = Int(piece[..<end]),
                  slot >= 0, slot < arguments.count else { return "{" + piece }
            return arguments[slot] + piece[piece.index(after: end)...]
        }.joined()
    }
    public static func resource(_ name: String, extension ext: String, bundle: Bundle = .main) -> URL? {
        // Explicit paths avoid falling back to the Chinese bitmap in English mode.
        if current == .english, let path = bundle.resourceURL?.appendingPathComponent("en.lproj").appendingPathComponent(name + "." + ext),
           FileManager.default.fileExists(atPath: path.path) { return path }
        return bundle.resourceURL.map { $0.appendingPathComponent(name + "." + ext) }.flatMap { FileManager.default.fileExists(atPath: $0.path) ? $0 : nil }
            ?? bundle.url(forResource: name, withExtension: ext, subdirectory: nil, localization: "zh-Hans")
            ?? bundle.url(forResource: name, withExtension: ext)
    }
    public static let english: [String: String] = [
ENTRIES
    ]
}
'''.replace('ENTRIES',entries)
(root/'Sources/MacOSXCore/AppLanguage.swift').write_text(source)
print(len(en),'translations; placeholders validated')
